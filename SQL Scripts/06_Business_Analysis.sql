-- 2. FIND THE TOP 10 COUNTRIES WITH THE HIGHEST NUMBER OF TITLES AVAILABLE ON NETFLIX ?

SELECT TOP 10 
COUNTRY ,
COUNT (*) AS TOTAL_TITLES 
FROM NETFLIX 
GROUP BY COUNTRY 
ORDER BY TOTAL_TITLES DESC

--BUSINESS INSIGHT 
--1. US HAVE THE HIGHEST NUBER OF TITLES AVAILABLE ON NETFLIX 
--2. MAXICO HAVE THE LOWEST TITLES AVAILABLE ON NETFLIX 

