--4 .HOW MANY TITLES WERE ADDED EACH YEAR AND WHICH YEAR HAD THE HIGHEST GROWTH ?
  
 SELECT TOP 1
 YEAR(DATE_ADDED) AS Added,
 COUNT(*) AS TOTAL_TITILES 
FROM NETFLIX 
WHERE DATE_ADDED IS NOT NULL
GROUP BY YEAR(DATE_ADDED)
ORDER BY TOTAL_TITILES DESC;

--BUSINESS INSIGHT 
-- 1. 2016 TITLES ADDED EACH YEAR 
--2 . 2019 WAS THE HIGHEST GROWTH 

