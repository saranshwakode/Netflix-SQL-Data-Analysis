--WHICH 10 GENRES SHOULD NETFLIX FOCUS ON IF THE GOAL IS TO INVEST IN THE MOST POPULAR CONTENT CATOGORIES ?
WITH GENRE_COUNT AS
( 
SELECT 
TRIM(VALUE)  AS GENRE,
COUNT (*)  AS TOTAL_TITLES 
FROM NETFLIX 
CROSS APPLY STRING_SPLIT(LISTED_IN, ',')
GROUP BY TRIM(VALUE) 
) 
SELECT TOP 10 
GENRE,
TOTAL_TITLES 
FROM GENRE_COUNT 
ORDER BY TOTAL_TITLES DESC 

