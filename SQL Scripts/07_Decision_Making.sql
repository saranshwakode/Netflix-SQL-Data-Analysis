 --6. WHICH YEARS EXPIERECE THE LARGEST INCREASE IN CONTENT ADDITIONS ? WHAT DOES THIS SUGGEST ABOUT NETFLIX CONTENT EXPANSION STRTEGY ?
WITH YEARLY_COUNT AS
(
SELECT
YEAR(DATE_ADDED) AS YEAR,
COUNT(*) AS TITLE_COUNT
FROM NETFLIX
WHERE DATE_ADDED IS NOT NULL
GROUP BY YEAR(DATE_ADDED)
),
YEARLY_INCREASE AS
(
SELECT
YEAR,
TITLE_COUNT,
LAG(TITLE_COUNT) OVER (ORDER BY YEAR) AS PREVIOUS_YEAR_COUNT
FROM YEARLY_COUNT
)
SELECT
YEAR,
TITLE_COUNT,
PREVIOUS_YEAR_COUNT,
TITLE_COUNT - PREVIOUS_YEAR_COUNT AS INCREASE
FROM YEARLY_INCREASE
ORDER BY INCREASE DESC;

