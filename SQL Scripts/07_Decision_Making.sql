-- 3. WHICH COUNTRIES HAVE A HIGHER PROPOTION OF TV SHOWS THAN MOVIES INDICATING AN OPPORTUNITY TO STRENGTHEN TV CONTENT ?
WITH COUNTRY_TYPE AS
(
SELECT
TRIM(VALUE) AS COUNTRY,
TYPE,
COUNT(*) AS TITLE_COUNT
FROM NETFLIX
CROSS APPLY STRING_SPLIT(COUNTRY, ',')
WHERE COUNTRY IS NOT NULL
GROUP BY TRIM(VALUE), TYPE
)
SELECT
COUNTRY,
SUM(CASE WHEN TYPE = 'Movie' THEN TITLE_COUNT ELSE 0 END) AS MOVIES,
SUM(CASE WHEN TYPE = 'TV Show' THEN TITLE_COUNT ELSE 0 END) AS TV_SHOWS
FROM COUNTRY_TYPE
GROUP BY COUNTRY
HAVING SUM(CASE WHEN TYPE = 'TV Show' THEN TITLE_COUNT ELSE 0 END)
> SUM(CASE WHEN TYPE = 'Movie' THEN TITLE_COUNT ELSE 0 END)
ORDER BY TV_SHOWS DESC;

----------------------------------------------BUSINESS INSIGHT--------------------------------------------------------

--NETFLIX CAN FOCUS ON COUNTRIES WHERE TV CONTENT IS ALREADY STONG CAUSE THE VIEWRS OF THAT SPECIFIC COUNTRIRES ARE ALREADY DEVLOPED 
-- NETFLIX CAN STRENGHTHEN TV CONTENT IN COUNTRIES WHERE TV SHOWS ALREADY HAVE A STONG PRESENECE THAN MOVIES 

